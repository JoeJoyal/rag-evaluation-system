
import os
from dotenv import load_dotenv
from pydantic import BaseModel

from langchain_groq import ChatGroq

from deepeval.models import DeepEvalBaseLLM
from deepeval.metrics import FaithfulnessMetric
from deepeval.test_case import LLMTestCase


# --------------------------------------------------
# 1. Load Groq API key
# --------------------------------------------------

load_dotenv()

GROQ_API_KEY = os.getenv("GROQ_API_KEY")

if not GROQ_API_KEY:
    raise ValueError("GROQ_API_KEY is missing in .env")


# --------------------------------------------------
# 2. Create a Groq model adapter for DeepEval
# --------------------------------------------------

class GroqDeepEvalModel(DeepEvalBaseLLM):

    def __init__(self, model_name, api_key):

        self.model_name = model_name

        self.llm = ChatGroq(
            model=model_name,
            api_key=api_key,
            temperature=0,
            max_tokens=800
        )

    def load_model(self):
        return self.llm

    def get_model_name(self):
        return self.model_name

    def generate(self, prompt: str, schema=None):

        if schema is not None:
            return self.llm.with_structured_output(schema).invoke(prompt)

        return self.llm.invoke(prompt).content

    async def a_generate(self, prompt: str, schema=None):

        if schema is not None:
            return await self.llm.with_structured_output(schema).ainvoke(prompt)

        response = await self.llm.ainvoke(prompt)

        return response.content


# --------------------------------------------------
# 3. Initialize Groq as the evaluation judge
# --------------------------------------------------

judge_model = GroqDeepEvalModel(
    model_name="qwen/qwen3.8-27b",
    api_key=GROQ_API_KEY
)


# --------------------------------------------------
# 4. Define the user's question
# --------------------------------------------------

question = (
    "Which company did Joe work for as a Generative AI Engineer, "
    "and what RAG work did he perform?"
)


# --------------------------------------------------
# 5. Actual answer generated by your RAG application
# --------------------------------------------------

actual_output = (
    "Joe worked as a Generative AI Engineer at Rangsons Aerospace "
    "Pvt Ltd from August 2025 to September 2026. He architected "
    "scalable RAG pipelines using LangChain and vector databases "
    "such as Pinecone, ChromaDB, pgvector, and Weaviate to improve "
    "response accuracy using enterprise knowledge sources."
)


# --------------------------------------------------
# 6. Retrieved context from the resume PDF
# --------------------------------------------------

retrieval_context = [
    """
    Generative AI Engineer
    Aug 2025 - Sep 2026
    Rangsons Aerospace Pvt Ltd | Bangalore, India

    Architected scalable RAG pipelines using LangChain and
    vector databases (Pinecone, ChromaDB, pgvector, Weaviate)
    to improve response accuracy using enterprise knowledge sources.
    """
]


# --------------------------------------------------
# 7. Create DeepEval test case
# --------------------------------------------------

test_case = LLMTestCase(
    input=question,
    actual_output=actual_output,
    retrieval_context=retrieval_context
)


# --------------------------------------------------
# 8. Configure Faithfulness metric
# --------------------------------------------------

metric = FaithfulnessMetric(
    threshold=0.7,
    model=judge_model,
    include_reason=True
)


# --------------------------------------------------
# 9. Execute evaluation
# --------------------------------------------------

metric.measure(test_case)

print("\n========== FAITHFULNESS EVALUATION ==========")
print("Question:", question)
print("Actual Answer:", actual_output)
print("Score:", metric.score)
print("Reason:", metric.reason)
print("Passed:", metric.is_successful())
